          <p>
            很多人遇到離婚或分居時，第一個問題是：「小孩會判給誰？」
          </p>
          <p>
            但在臺灣法律上，法院真正處理的不是父母之間誰輸誰贏，而是未成年子女的權利義務應由誰行使或負擔、孩子由誰負責主要照顧，以及另一方如何與孩子會面交往。
